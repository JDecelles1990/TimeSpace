"""AutoHotkey v2 process runner, executable detection, and strict v2 code generator."""
import datetime
import os
import shutil
import sys
from typing import List, Optional, Tuple

from PySide6.QtCore import QObject, QProcess, Signal

from src.config import AHKHotstringItem


def find_ahk_v2_exe(custom_path: str = "") -> Optional[str]:
    """
    Locate an AutoHotkey v2 executable on Windows.
    Strictly avoids legacy v1 executables (e.g., v1.1.*).
    """
    # 1. Custom user-specified path
    if custom_path and os.path.isfile(custom_path):
        norm = os.path.normpath(custom_path)
        if "v1." not in norm.lower():
            return norm

    # 2. Standard Windows 64-bit / 32-bit install paths
    candidates = [
        r"C:\Program Files\AutoHotkey\v2\AutoHotkey64.exe",
        r"C:\Program Files\AutoHotkey\v2\AutoHotkey.exe",
        r"C:\Program Files\AutoHotkey\v2\AutoHotkey32.exe",
        os.path.expandvars(r"%LOCALAPPDATA%\Programs\AutoHotkey\v2\AutoHotkey64.exe"),
        os.path.expandvars(r"%LOCALAPPDATA%\Programs\AutoHotkey\v2\AutoHotkey.exe"),
        os.path.expandvars(r"%LOCALAPPDATA%\Programs\AutoHotkey\v2\AutoHotkey32.exe"),
        r"C:\Program Files (x86)\AutoHotkey\v2\AutoHotkey32.exe",
    ]

    for cand in candidates:
        if os.path.isfile(cand):
            return os.path.normpath(cand)

    # 3. PATH lookup (verify not v1)
    for bin_name in ["AutoHotkey64.exe", "AutoHotkey.exe", "AutoHotkey32.exe"]:
        found = shutil.which(bin_name)
        if found and os.path.isfile(found):
            norm = os.path.normpath(found)
            # Ensure it's not a legacy v1 directory
            if "v1." not in norm.lower():
                return norm

    return None


def clean_hotstring_trigger(raw_trigger: str) -> str:
    """Strip leading and trailing colons from trigger abbreviations."""
    cleaned = raw_trigger.strip()
    while cleaned.startswith(":"):
        cleaned = cleaned[1:]
    while cleaned.endswith(":"):
        cleaned = cleaned[:-1]
    return cleaned.strip()


def normalize_hotstring_options(raw_options: str, is_expression: bool = False) -> str:
    """Ensure options are valid AHK v2 option flags without redundant colons."""
    opts = raw_options.replace(":", "").strip()
    if is_expression and "X" not in opts and "x" not in opts:
        opts += "X"
    return opts


def generate_ahk_v2_script(items: List[AHKHotstringItem]) -> str:
    """
    Generate a 100% compliant AutoHotkey v2 script from structured items.
    Strictly follows AutoHotkey v2.0+ specifications (no legacy v1 syntax).
    """
    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    lines: List[str] = [
        "; ==============================================================================",
        "; TimeSpace AutoHotkey v2 Hotstrings Text Expander Script",
        f"; Generated by TimeSpace on {now_str}",
        "; Strictly AutoHotkey v2.0+ syntax (Zero legacy v1 code)",
        "; ==============================================================================",
        "#Requires AutoHotkey v2.0+",
        "#SingleInstance Force",
        "SetWorkingDir A_InitialWorkingDir",
        "",
        "; ------------------------------------------------------------------------------",
        "; Hotstrings Definitions",
        "; ------------------------------------------------------------------------------",
    ]

    for idx, item in enumerate(items, 1):
        trig = clean_hotstring_trigger(item.trigger)
        if not trig:
            continue

        opts = normalize_hotstring_options(item.options, item.is_expression)
        rep = item.replacement
        desc = item.description.strip()

        header_comment = f"; #{idx} — {desc}" if desc else f"; #{idx}"

        if not item.enabled:
            # Comment out disabled hotstring
            lines.append(f"; [DISABLED] {header_comment}")
            if "\n" in rep:
                lines.append(f"; :{opts}:{trig}::")
                lines.append("; (")
                for sub in rep.splitlines():
                    lines.append(f"; {sub}")
                lines.append("; )")
            else:
                lines.append(f"; :{opts}:{trig}::{rep}")
            lines.append("")
            continue

        lines.append(header_comment)

        if item.is_expression or ("X" in opts or "x" in opts):
            # AutoHotkey v2 function / expression execution
            lines.append(f":{opts}:{trig}::{rep}")
        elif "\n" in rep:
            # Multi-line text expansion using AHK v2 continuation section
            lines.append(f":{opts}:{trig}::")
            lines.append("(")
            for sub in rep.splitlines():
                lines.append(sub)
            lines.append(")")
        else:
            # Single-line replacement
            lines.append(f":{opts}:{trig}::{rep}")

        lines.append("")

    return "\n".join(lines).strip() + "\n"


class AHKProcessManager(QObject):
    """
    Manages the lifecycle of the external AutoHotkey v2 process via QProcess.
    Thread-safe and marshaled directly onto the Qt event loop.
    """
    statusChanged = Signal(bool, int)      # (is_running, pid)
    errorOccurred = Signal(str)           # error_message
    outputReceived = Signal(str)          # standard error / output

    def __init__(self, parent: Optional[QObject] = None) -> None:
        super().__init__(parent)
        self._process: Optional[QProcess] = None
        self._current_script_path: str = ""
        self._current_exe_path: str = ""

    def is_running(self) -> bool:
        if self._process is None:
            return False
        return self._process.state() == QProcess.ProcessState.Running

    def get_pid(self) -> int:
        if self.is_running() and self._process is not None:
            return int(self._process.processId())
        return 0

    def get_exe_path(self) -> str:
        return self._current_exe_path

    def get_script_path(self) -> str:
        return self._current_script_path

    def start_script(self, script_path: str, custom_exe: str = "") -> bool:
        """Launch or reload the AutoHotkey v2 script."""
        exe = find_ahk_v2_exe(custom_exe)
        if not exe:
            err = "AutoHotkey v2 executable not found. Please install AHK v2 or set its path in Settings."
            self.errorOccurred.emit(err)
            return False

        if not os.path.isfile(script_path):
            err = f"Script file not found: {script_path}"
            self.errorOccurred.emit(err)
            return False

        self._current_exe_path = exe
        self._current_script_path = os.path.abspath(script_path)

        # Stop existing process if already tracked
        if self.is_running():
            self.stop_script()

        proc = QProcess(self)
        self._process = proc

        proc.started.connect(self._on_started)
        proc.finished.connect(self._on_finished)
        proc.readyReadStandardError.connect(self._on_stderr)
        proc.readyReadStandardOutput.connect(self._on_stdout)

        work_dir = os.path.dirname(self._current_script_path) or None
        if work_dir and os.path.isdir(work_dir):
            proc.setWorkingDirectory(work_dir)

        proc.start(self._current_exe_path, [self._current_script_path])
        started = proc.waitForStarted(2000)
        if not started:
            err = f"Failed to start AutoHotkey v2 process: {proc.errorString()}"
            self.errorOccurred.emit(err)
            return False

        return True

    def reload_script(self) -> bool:
        """Reload the active script using current paths."""
        if not self._current_script_path or not os.path.isfile(self._current_script_path):
            return False
        return self.start_script(self._current_script_path, self._current_exe_path)

    def stop_script(self) -> bool:
        """Terminate the active AutoHotkey v2 script process."""
        if self._process is None or not self.is_running():
            self.statusChanged.emit(False, 0)
            return True

        self._process.terminate()
        if not self._process.waitForFinished(1500):
            self._process.kill()
            self._process.waitForFinished(1000)

        self.statusChanged.emit(False, 0)
        return True

    def _on_started(self) -> None:
        pid = self.get_pid()
        self.statusChanged.emit(True, pid)

    def _on_finished(self, exit_code: int, exit_status: QProcess.ExitStatus) -> None:
        self.statusChanged.emit(False, 0)

    def _on_stderr(self) -> None:
        if self._process:
            data = bytes(self._process.readAllStandardError()).decode("utf-8", errors="replace")
            if data.strip():
                self.outputReceived.emit(data.strip())

    def _on_stdout(self) -> None:
        if self._process:
            data = bytes(self._process.readAllStandardOutput()).decode("utf-8", errors="replace")
            if data.strip():
                self.outputReceived.emit(data.strip())

